//! Police de l'interface, dessinee point par point pour le jeu.
//!
//! Les lettres font cinq points de large au plus et sept de haut, plus une rangee pour les jambages
//! (g, p, q, y) ; les accents des capitales depassent de deux rangees vers le haut. Un point de police
//! vaut une unite d'interface : la police est donc nette a toutes les echelles, sans arrondi ni lissage.
//!
//! Chaque dessin est une liste de rangees, de haut en bas ; '#' est un point plein.

/// Hauteur d'une ligne, en points : sept pour les lettres, un pour les jambages.
pub const HEIGHT: usize = 8;

/// Dessin d'un caractere : ses rangees, et la rangee de la ligne ou commence la premiere (0 = haut des capitales).
pub struct Shape {
    pub rows: Vec<String>,
    pub top: i32,
}

fn own(rows: &[&str]) -> Vec<String> {
    rows.iter().map(|r| r.to_string()).collect()
}

