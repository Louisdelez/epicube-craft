/// Signe place au-dessus d'une lettre : ses deux rangees.
fn mark(kind: char) -> [&'static str; 2] {
    match kind {
        '\'' => ["...#.", "..#.."],
        '`' => [".#...", "..#.."],
        '^' => ["..#..", ".#.#."],
        _ => [".#.#.", "....."],
    }
}

/// (lettre de base, signe) d'un caractere accentue ; ',' est la cedille.
fn accented(ch: char) -> Option<(char, char)> {
    Some(match ch {
        'é' => ('e', '\''),
        'è' => ('e', '`'),
        'ê' => ('e', '^'),
        'ë' => ('e', ':'),
        'à' => ('a', '`'),
        'â' => ('a', '^'),
        'ä' => ('a', ':'),
        'î' => ('i', '^'),
        'ï' => ('i', ':'),
        'ô' => ('o', '^'),
        'ö' => ('o', ':'),
        'ù' => ('u', '`'),
        'û' => ('u', '^'),
        'ü' => ('u', ':'),
        'ç' => ('c', ','),
        'É' => ('E', '\''),
        'È' => ('E', '`'),
        'Ê' => ('E', '^'),
        'À' => ('A', '`'),
        'Â' => ('A', '^'),
        'Î' => ('I', '^'),
        'Ô' => ('O', '^'),
        'Ù' => ('U', '`'),
        'Û' => ('U', '^'),
        'Ç' => ('C', ','),
        _ => return None,
    })
}

/// Dessin d'un caractere, ou None s'il n'est pas dans la police.
pub fn shape(ch: char) -> Option<Shape> {
    if let Some(rows) = base(ch) {
        return Some(Shape { rows: own(rows), top: 0 });
    }
    let (letter, kind) = accented(ch)?;
    let mut rows = own(base(letter)?);
    if kind == ',' {
        // Cedille : un point sous la lettre, dans la rangee des jambages.
        rows.resize(HEIGHT, String::new());
        rows[HEIGHT - 1] = "..#..".to_string();
        return Some(Shape { rows, top: 0 });
    }
    let [a, b] = mark(kind);
    if letter == 'i' {
        // Le i perd son point : le signe, sur trois points de large, prend sa place.
        let (a, b) = match kind {
            '^' => (".#.", "#.#"),
            _ => ("#.#", "..."),
        };
        let mut out = vec![a.to_string(), b.to_string()];
        out.extend((0..5).map(|_| ".#.".to_string()));
        return Some(Shape { rows: out, top: 0 });
    }
    if letter.is_lowercase() {
        // Les deux rangees du haut d'une minuscule sont libres.
        rows[0] = a.to_string();
        rows[1] = b.to_string();
        return Some(Shape { rows, top: 0 });
    }
    // Capitale : le signe depasse au-dessus de la ligne. Sur le I, etroit, il se resserre.
    let (a, b) = if letter == 'I' { (".#.", "#.#") } else { (a, b) };
    let mut out = vec![a.to_string(), b.to_string()];
    out.extend(rows);
    Some(Shape { rows: out, top: -2 })
}

/// Largeur d'un dessin, en points.
pub fn width(shape: &Shape) -> usize {
    shape.rows.iter().map(|r| r.len()).max().unwrap_or(0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_character_the_game_writes_has_a_shape() {
        // Tout l'ASCII affichable, et les lettres accentuees du francais.
        for ch in (32u8..127).map(|b| b as char).chain("éèêëàâäîïôöùûüçÉÈÊÀÂÎÔÙÛÇ«»°×".chars()) {
            let s = shape(ch).unwrap_or_else(|| panic!("pas de dessin pour {ch:?}"));
            let w = width(&s);
            assert!((1..=5).contains(&w), "{ch:?} : largeur {w}");
            assert!(s.rows.len() <= HEIGHT + 2 && s.top >= -2, "{ch:?} : trop haut");
            assert!(s.rows.iter().all(|r| r.chars().all(|c| c == '#' || c == '.')), "{ch:?} : caractere parasite");
            // Rien sous la rangee des jambages.
            assert!(s.top + s.rows.len() as i32 <= HEIGHT as i32, "{ch:?} deborde sous la ligne");
            if ch != ' ' {
                assert!(s.rows.iter().any(|r| r.contains('#')), "{ch:?} est vide");
            }
        }
        // Les lettres se distinguent les unes des autres.
        let mut seen = std::collections::HashMap::new();
        for ch in (33u8..127).map(|b| b as char) {
            let s = shape(ch).unwrap();
            let key = format!("{}|{:?}", s.top, s.rows.iter().map(|r| format!("{r:.<5}")).collect::<Vec<_>>());
            if let Some(other) = seen.insert(key, ch) {
                panic!("{ch:?} et {other:?} ont le meme dessin");
            }
        }
    }

    #[test]
    fn accents_sit_above_their_letter() {
        // Minuscule : le signe occupe les deux rangees libres, la lettre ne bouge pas.
        let (e, plain) = (shape('é').unwrap(), shape('e').unwrap());
        assert_eq!(e.top, 0);
        assert_eq!(e.rows[2..], plain.rows[2..]);
        assert!(e.rows[0].contains('#'));
        // Capitale : la lettre reste entiere, le signe depasse de deux rangees.
        let (cap, plain) = (shape('É').unwrap(), shape('E').unwrap());
        assert_eq!(cap.top, -2);
        assert_eq!(cap.rows[2..], plain.rows[..]);
        // Cedille dans la rangee des jambages ; i sans son point.
        assert_eq!(shape('ç').unwrap().rows[7], "..#..");
        assert_eq!(width(&shape('î').unwrap()), 3);
        assert!(shape('🙂').is_none());
    }
}
